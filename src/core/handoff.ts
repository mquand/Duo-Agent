import fs from 'fs-extra';
import path from 'path';

export interface HandoffStepInput {
  id?: number;
  title: string;
  files?: string[];
  instruction: string;
  verification?: string;
}

export interface HandoffStep {
  id: number;
  title: string;
  status: 'pending' | 'in_progress' | 'completed' | 'failed';
  files: string[];
  instruction: string;
  verification: string;
  completedAt?: string;
  note?: string;
}

export interface HandoffPlan {
  version: '1.0';
  title: string;
  task: string;
  summary: string;
  planner: string;
  executor: string;
  createdAt: string;
  updatedAt: string;
  conventions?: string;
  steps: HandoffStep[];
}

export class HandoffManager {
  private static getHandoffDir(baseDir: string = process.cwd()): string {
    return path.join(path.resolve(baseDir), '.duo');
  }

  private static getPlanJsonPath(baseDir: string = process.cwd()): string {
    return path.join(this.getHandoffDir(baseDir), 'handoff.json');
  }

  private static getPlanMarkdownPath(baseDir: string = process.cwd()): string {
    return path.join(path.resolve(baseDir), 'PLAN.md');
  }

  /**
   * Format the plan as a clean, interactive Markdown checklist
   */
  static formatPlanMarkdown(plan: HandoffPlan): string {
    const lines: string[] = [
      `# 📋 PLAN: ${plan.title}`,
      '',
      `> **Task**: ${plan.task}`,
      `> **Planner**: ${plan.planner} ➔ **Executor**: ${plan.executor}`,
      `> **Updated**: ${new Date(plan.updatedAt).toLocaleString()}`,
      '',
      '## 📝 Summary',
      plan.summary,
      '',
    ];

    if (plan.conventions && plan.conventions.trim().length > 0) {
      lines.push('## ⚠️ Conventions & Requirements');
      lines.push(plan.conventions);
      lines.push('');
    }

    lines.push('## 🚀 Action Checklist');
    for (const step of plan.steps) {
      const check = step.status === 'completed' ? '[x]' : step.status === 'in_progress' ? '[/]' : '[ ]';
      const statusBadge =
        step.status === 'completed'
          ? '*(Completed)*'
          : step.status === 'in_progress'
          ? '*(IN PROGRESS)*'
          : step.status === 'failed'
          ? '*(FAILED)*'
          : '';

      lines.push(`- ${check} **Step ${step.id}: ${step.title}** ${statusBadge}`.trim());
      if (step.files && step.files.length > 0) {
        lines.push(`  - **Files**: ${step.files.map((f: string) => "`" + f + "`").join(', ')}`);
      }
      lines.push(`  - **Instruction**: ${step.instruction}`);
      if (step.verification) {
        lines.push(`  - **Verification**: ${step.verification}`);
      }
      if (step.note) {
        lines.push(`  - **Note**: ${step.note}`);
      }
    }

    lines.push('');
    lines.push('---');
    lines.push('*Generated by Duo-Agent Multi-Agent Orchestrator*');

    return lines.join('\n');
  }

  /**
   * Save or overwrite a handoff plan
   */
  static async savePlan(params: {
    title: string;
    task: string;
    summary: string;
    steps: HandoffStepInput[];
    conventions?: string;
    directory?: string;
    planner?: string;
    executor?: string;
  }): Promise<{ plan: HandoffPlan; planMarkdownPath: string; planJsonPath: string }> {
    const cwd = params.directory ? path.resolve(params.directory) : process.cwd();
    const handoffDir = this.getHandoffDir(cwd);
    await fs.ensureDir(handoffDir);

    const now = new Date().toISOString();
    const steps: HandoffStep[] = params.steps.map((s, index) => ({
      id: s.id || index + 1,
      title: s.title,
      status: 'pending',
      files: s.files || [],
      instruction: s.instruction,
      verification: s.verification || '',
    }));

    const plan: HandoffPlan = {
      version: '1.0',
      title: params.title,
      task: params.task,
      summary: params.summary,
      planner: params.planner || 'Architect / Planner',
      executor: params.executor || 'Builder / Executor',
      createdAt: now,
      updatedAt: now,
      conventions: params.conventions,
      steps,
    };

    const jsonPath = this.getPlanJsonPath(cwd);
    const mdPath = this.getPlanMarkdownPath(cwd);

    await fs.writeJson(jsonPath, plan, { spaces: 2 });
    await fs.writeFile(mdPath, this.formatPlanMarkdown(plan), 'utf-8');

    return { plan, planMarkdownPath: mdPath, planJsonPath: jsonPath };
  }

  /**
   * Retrieve active handoff plan
   */
  static async getPlan(directory?: string): Promise<HandoffPlan | null> {
    const cwd = directory ? path.resolve(directory) : process.cwd();
    const jsonPath = this.getPlanJsonPath(cwd);
    if (!(await fs.pathExists(jsonPath))) {
      return null;
    }
    return await fs.readJson(jsonPath);
  }

  /**
   * Update step status and synchronize PLAN.md
   */
  static async updateStepStatus(params: {
    stepId: number;
    status: 'pending' | 'in_progress' | 'completed' | 'failed';
    note?: string;
    directory?: string;
  }): Promise<{ plan: HandoffPlan; planMarkdownPath: string }> {
    const cwd = params.directory ? path.resolve(params.directory) : process.cwd();
    const plan = await this.getPlan(cwd);
    if (!plan) {
      throw new Error(`No active handoff plan found in directory: ${cwd}`);
    }

    const step = plan.steps.find((s) => s.id === params.stepId);
    if (!step) {
      throw new Error(`Step ID ${params.stepId} not found in plan.`);
    }

    step.status = params.status;
    if (params.note) step.note = params.note;
    if (params.status === 'completed') {
      step.completedAt = new Date().toISOString();
    }
    plan.updatedAt = new Date().toISOString();

    const jsonPath = this.getPlanJsonPath(cwd);
    const mdPath = this.getPlanMarkdownPath(cwd);

    await fs.writeJson(jsonPath, plan, { spaces: 2 });
    await fs.writeFile(mdPath, this.formatPlanMarkdown(plan), 'utf-8');

    return { plan, planMarkdownPath: mdPath };
  }
}
